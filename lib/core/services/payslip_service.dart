import 'dart:io';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:path_provider/path_provider.dart';

import '../constants/app_constants.dart';
import '../models/payroll_model.dart';
import '../models/worker_model.dart';

/// Builds and saves a PDF payslip for a worker's monthly payroll.
class PayslipService {
  PayslipService._();
  static final PayslipService instance = PayslipService._();

  static const _monthNames = [
    'January',
    'February',
    'March',
    'April',
    'May',
    'June',
    'July',
    'August',
    'September',
    'October',
    'November',
    'December',
  ];

  /// Generates the payslip PDF for [worker]/[payroll] and saves it to disk.
  /// Returns the saved [File] so the caller can open or share it.
  Future<File> generatePayslip({
    required WorkerModel worker,
    required PayrollModel payroll,
  }) async {
    final monthLabel =
        '${_monthNames[payroll.month.month - 1]} ${payroll.month.year}';
    final generatedOn = DateTime.now();

    final doc = pw.Document();

    doc.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (context) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            _buildHeader(context, monthLabel),
            pw.SizedBox(height: 16),
            pw.Divider(thickness: 1, color: PdfColors.grey400),
            pw.SizedBox(height: 16),
            _buildWorkerInfo(worker, payroll, generatedOn),
            pw.SizedBox(height: 20),
            pw.Text(
              'Salary Breakdown',
              style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold),
            ),
            pw.SizedBox(height: 8),
            _buildSalaryTable(payroll),
            pw.SizedBox(height: 20),
            _buildNetSalaryBanner(payroll),
            pw.SizedBox(height: 32),
            pw.Divider(thickness: 0.5, color: PdfColors.grey400),
            pw.SizedBox(height: 8),
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text(
                  'This is a system-generated payslip and does not require '
                  'a signature.',
                  style:
                      const pw.TextStyle(fontSize: 8, color: PdfColors.grey600),
                ),
                pw.Text(
                  'Generated by ${AppConstants.appName}',
                  style:
                      const pw.TextStyle(fontSize: 8, color: PdfColors.grey600),
                ),
              ],
            ),
          ],
        ),
      ),
    );

    final bytes = await doc.save();
    return _saveToFile(bytes, worker, payroll);
  }

  pw.Widget _buildHeader(pw.Context context, String monthLabel) {
    return pw.Row(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
      children: [
        pw.Container(
          width: 48,
          height: 48,
          decoration: pw.BoxDecoration(
            color: PdfColors.blue800,
            borderRadius: pw.BorderRadius.circular(8),
          ),
          child: pw.Center(
            child: pw.Text(
              'WB',
              style: pw.TextStyle(
                fontSize: 20,
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.white,
              ),
            ),
          ),
        ),
        pw.SizedBox(width: 12),
        pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(
              AppConstants.appName,
              style: pw.TextStyle(
                  fontSize: 18, fontWeight: pw.FontWeight.bold),
            ),
            pw.Text(
              'Site & Worker Management',
              style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
            ),
          ],
        ),
      ],
    );
  }

  pw.Widget _buildWorkerInfo(
    WorkerModel worker,
    PayrollModel payroll,
    DateTime generatedOn,
  ) {
    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.all(12),
      decoration: pw.BoxDecoration(
        color: PdfColors.grey100,
        borderRadius: pw.BorderRadius.circular(6),
      ),
      child: pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Expanded(
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                _infoRow('Worker', worker.name),
                _infoRow('Trade', worker.trade),
                _infoRow('Phone', worker.phone.isEmpty ? '-' : worker.phone),
              ],
            ),
          ),
          pw.Expanded(
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                _infoRow('Status', payroll.isPaid ? 'Paid' : 'Draft'),
                _infoRow('Days Worked', '${payroll.totalDaysWorked}'),
                _infoRow('Generated', _formatDate(generatedOn)),
              ],
            ),
          ),
        ],
      ),
    );
  }

  pw.Widget _infoRow(String label, String value) {
    return pw.Padding(
      padding: const pw.EdgeInsets.only(bottom: 4),
      child: pw.Row(
        children: [
          pw.SizedBox(
            width: 80,
            child: pw.Text(
              label,
              style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
            ),
          ),
          pw.Text(
            value,
            style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold),
          ),
        ],
      ),
    );
  }

  pw.Widget _buildSalaryTable(PayrollModel payroll) {
    final rows = <List<String>>[
      [
        'Full Days (${payroll.fullDays} x ${_currency(payroll.dailyRate)})',
        _currency(payroll.fullDays * payroll.dailyRate),
      ],
      [
        'Half Days (${payroll.halfDays} x ${_currency(payroll.dailyRate / 2)})',
        _currency(payroll.halfDays * (payroll.dailyRate / 2)),
      ],
      ['Base Wage', _currency(payroll.baseWage)],
      [
        'Overtime (${payroll.overtimeHours.toStringAsFixed(1)} hrs x '
            '${_currency(payroll.overtimeRate)})',
        _currency(payroll.overtimePay),
      ],
      ['Bonus', _currency(payroll.bonus)],
      ['Gross Salary', _currency(payroll.grossSalary)],
      ['Advance Deducted', '- ${_currency(payroll.advanceAmount)}'],
      ['Other Deductions', '- ${_currency(payroll.deductions)}'],
    ];

    return pw.TableHelper.fromTextArray(
      headers: const ['Description', 'Amount'],
      data: rows,
      headerStyle: pw.TextStyle(
        fontWeight: pw.FontWeight.bold,
        fontSize: 10,
        color: PdfColors.white,
      ),
      headerDecoration: const pw.BoxDecoration(color: PdfColors.blueGrey800),
      cellStyle: const pw.TextStyle(fontSize: 10),
      cellAlignments: {
        0: pw.Alignment.centerLeft,
        1: pw.Alignment.centerRight,
      },
      cellPadding: const pw.EdgeInsets.symmetric(horizontal: 8, vertical: 6),
      border: pw.TableBorder.all(color: PdfColors.grey300, width: 0.5),
      columnWidths: {
        0: const pw.FlexColumnWidth(3),
        1: const pw.FlexColumnWidth(2),
      },
    );
  }

  pw.Widget _buildNetSalaryBanner(PayrollModel payroll) {
    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.symmetric(horizontal: 16, vertical: 12),
      decoration: pw.BoxDecoration(
        color: PdfColors.green50,
        border: pw.Border.all(color: PdfColors.green300),
        borderRadius: pw.BorderRadius.circular(6),
      ),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text(
            'NET SALARY',
            style: pw.TextStyle(fontSize: 12, fontWeight: pw.FontWeight.bold),
          ),
          pw.Text(
            _currency(payroll.netSalary),
            style: pw.TextStyle(
              fontSize: 16,
              fontWeight: pw.FontWeight.bold,
              color: PdfColors.green800,
            ),
          ),
        ],
      ),
    );
  }

  /// Matches the currency formatting used by [CurrencyText] in the app UI.
  String _currency(double amount) {
    final abs = amount.abs();
    final str = abs.toStringAsFixed(0);
    final buf = StringBuffer();
    var count = 0;
    for (var i = str.length - 1; i >= 0; i--) {
      if (count > 0 && count % 3 == 0) buf.write(',');
      buf.write(str[i]);
      count++;
    }
    final formatted =
        (amount < 0 ? '-' : '') + buf.toString().split('').reversed.join();
    return '${AppConstants.currencySymbol} $formatted';
  }

  String _formatDate(DateTime d) {
    final month = _monthNames[d.month - 1].substring(0, 3);
    return '${d.day.toString().padLeft(2, '0')}-$month-${d.year}';
  }

  Future<File> _saveToFile(
    List<int> bytes,
    WorkerModel worker,
    PayrollModel payroll,
  ) async {
    final dir = await getApplicationDocumentsDirectory();
    final payslipsDir = Directory('${dir.path}/Payslips');
    if (!await payslipsDir.exists()) {
      await payslipsDir.create(recursive: true);
    }
    final safeName = worker.name.replaceAll(RegExp(r'[^A-Za-z0-9]+'), '_');
    final fileName = 'Payslip_${safeName}_${payroll.monthLabel}.pdf';
    final file = File('${payslipsDir.path}/$fileName');
    await file.writeAsBytes(bytes, flush: true);
    return file;
  }
}